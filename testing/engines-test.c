/* The compatibility matrix, worked out from app/engines.c for every pair of
 * known device profiles, and checks on the parts of it that matter.
 *
 *   cc -I app -o /tmp/engines-test testing/engines-test.c app/engines.c
 *   (make test runs it)
 *   /tmp/engines-test            checks; non-zero exit on a failure
 *   /tmp/engines-test --matrix   the matrix as Markdown (docs/engine-matrix.md)
 *
 * A profile lists what a device of that kind has out of the box. Add one per
 * new device or firmware; the matrix and these checks then cover it. */
#include "engines.h"
#include "../shim/gpsp_games.h"

#include <stdio.h>
#include <string.h>

typedef struct {
	const char* name;
	int tier;
	const char* arch;       /* 32, 64, 64+32 */
	const char* have;
	const char* install;
} Profile;

#define SPRUCE_CORES "fceumm,supafaust,snes9x,picodrive,genesis_plus_gx,gearsystem," \
	"gambatte-dual,gambatte-link,armgba-together,armgba-separate,mgba-dual,gpsp-link,pcsx_rearmed"
#define NEXTUI_CORES "fceumm,snes9x,supafaust,picodrive,gambatte-dual,gambatte-link,gpsp-link,pcsx_rearmed"

static const Profile PROFILES[] = {
	{ "spruce 64-bit",          3, "64+32", SPRUCE_CORES ",gearsystem-link", "" },
	{ "spruce A30",             2, "32",    SPRUCE_CORES ",gearsystem-link", "" },
	{ "spruce Mini",            1, "32",    SPRUCE_CORES ",gearsystem-link", "" },
	{ "NextUI 64-bit",          3, "64",    NEXTUI_CORES ",gearsystem-link", "mgba-dual" },
	{ "NextUI 64-bit + mGBA",   3, "64",    NEXTUI_CORES ",gearsystem-link,mgba-dual", "" },
	{ "NextUI A30",             2, "32",    "fceumm,supafaust,picodrive,gambatte-dual,gambatte-link,gpsp-link,pcsx_rearmed,gearsystem-link", "" },
};
#define PROFILE_COUNT ((int)(sizeof(PROFILES) / sizeof(PROFILES[0])))

static NS_EngineCaps caps_of(const Profile* p) {
	char text[1024];
	snprintf(text, sizeof(text), "tier=%d;arch=%s;have=%s;install=%s", p->tier, p->arch, p->have, p->install);
	NS_EngineCaps c;
	NS_engineCapsDecode(text, &c);
	return c;
}

static const char* resolve(int h, int g, const char* system, char* hint, size_t hint_len) {
	NS_EngineCaps hc = caps_of(&PROFILES[h]), gc = caps_of(&PROFILES[g]);
	int e = NS_engineResolve(system, &hc, &gc, hint, hint_len);
	return e < 0 ? "-" : NS_engineAt(e)->name;
}

static int find(const char* name) {
	for (int i = 0; i < PROFILE_COUNT; i++) if (!strcmp(PROFILES[i].name, name)) return i;
	return -1;
}

static int failures;

static void expect(const char* host, const char* guest, const char* system,
                   const char* engine, const char* hint) {
	char got_hint[64];
	const char* got = resolve(find(host), find(guest), system, got_hint, sizeof(got_hint));
	bool ok = !strcmp(got, engine) && (!hint || !strcmp(got_hint, hint));
	printf("  %s %s + %s, %s: %s%s%s\n", ok ? "ok  " : "FAIL", host, guest, system, got,
	       got_hint[0] ? " / " : "", got_hint);
	if (!ok) {
		printf("       want %s%s%s\n", engine, hint && hint[0] ? " / " : "", hint ? hint : "");
		failures++;
	}
}

static void matrix(void) {
	printf("# Engine matrix\n\n"
	       "Generated by `testing/engines-test.c --matrix` from the table in\n"
	       "`app/engines.c`: the engine a session runs for each system, host first.\n"
	       "`-` means no common engine, so each device runs its own core as before.\n"
	       "A note after `/` is the advice shown when a gpSP game is not linkable.\n");
	for (int h = 0; h < PROFILE_COUNT; h++) {
		for (int g = h; g < PROFILE_COUNT; g++) {
			printf("\n## %s + %s\n\n| System | Engine |\n|---|---|\n", PROFILES[h].name, PROFILES[g].name);
			for (int s = 0; s < NS_engineSystemCount(); s++) {
				char hint[64];
				const char* sys = NS_engineSystemAt(s);
				const char* e = resolve(h, g, sys, hint, sizeof(hint));
				printf("| %s | %s%s%s |\n", sys, e, hint[0] ? " / " : "", hint);
			}
		}
	}
}

int main(int argc, char** argv) {
	if (argc > 1 && !strcmp(argv[1], "--matrix")) { matrix(); return 0; }

	printf("== same-firmware pairs follow the tiers\n");
	expect("spruce 64-bit", "spruce 64-bit", "MS", "genesis_plus_gx", "");
	expect("spruce 64-bit", "spruce A30", "MS", "gearsystem", "");
	/* Gear-to-Gear: Netplay's own Gearsystem on every device, either word size. */
	expect("spruce 64-bit", "spruce 64-bit", "GG", "gearsystem-link", "");
	expect("spruce 64-bit", "NextUI 64-bit", "GG", "gearsystem-link", "");
	expect("NextUI 64-bit", "NextUI 64-bit", "GG", "gearsystem-link", "");
	expect("spruce 64-bit", "spruce A30", "GG", "gearsystem-link", "");
	expect("NextUI 64-bit", "NextUI A30", "GG", "gearsystem-link", "");
	expect("spruce Mini", "NextUI 64-bit", "GG", "gearsystem-link", "");
	expect("NextUI A30", "NextUI A30", "GG", "gearsystem-link", "");
	expect("spruce A30", "spruce Mini", "GBA", "armgba-separate", "");
	expect("spruce 64-bit", "spruce A30", "GBA", "armgba-together", "");
	expect("spruce Mini", "spruce Mini", "SFC", "supafaust", "");
	expect("spruce Mini", "spruce A30", "GB", "gambatte-dual", "");
	expect("spruce 64-bit", "spruce A30", "PS", "pcsx_rearmed", "");

	printf("== spruce and NextUI\n");
	expect("spruce 64-bit", "NextUI 64-bit + mGBA", "GBA", "mgba-dual", "");
	expect("spruce 64-bit", "NextUI 64-bit", "GBA", "gpsp-link", "install-mgba:guest");
	expect("NextUI 64-bit", "spruce 64-bit", "GBA", "gpsp-link", "install-mgba:host");
	expect("spruce A30", "NextUI 64-bit + mGBA", "GBA", "gpsp-link", "");
	expect("spruce Mini", "NextUI 64-bit", "GBA", "gpsp-link", "");
	expect("spruce 64-bit", "NextUI 64-bit", "MS", "picodrive", "");
	expect("spruce 64-bit", "NextUI 64-bit", "SFC", "supafaust", "");
	expect("spruce 64-bit", "NextUI 64-bit", "GBC", "gambatte-dual", "");
	expect("spruce A30", "NextUI 64-bit", "PS", "-", "");
	expect("NextUI 64-bit", "NextUI A30", "SFC", "supafaust", "");

	printf("== gpSP's link games\n");
	static const struct { const char* code; const char* title; bool links; } GAMES[] = {
		{ "AW2E", "", true }, { "BPEE", "", true }, { "AXVJ", "", true }, { "BMGE", "", true },
		{ "AMKE", "", false },                     /* Mario Kart Super Circuit */
		{ "XXXX", "POKEMON FIRE", true },          /* a hack keeping the title */
	};
	for (size_t i = 0; i < sizeof(GAMES) / sizeof(GAMES[0]); i++) {
		unsigned char header[0xC0];
		memset(header, 0, sizeof(header));
		memcpy(header + 0xA0, GAMES[i].title, strlen(GAMES[i].title));
		memcpy(header + 0xAC, GAMES[i].code, 4);
		bool got = gpsp_links_game(header, sizeof(header));
		printf("  %s %s%s%s -> %s\n", got == GAMES[i].links ? "ok  " : "FAIL", GAMES[i].code,
		       GAMES[i].title[0] ? " " : "", GAMES[i].title, got ? "links" : "does not link");
		if (got != GAMES[i].links) failures++;
	}

	printf("== caps round trip\n");
	NS_EngineCaps a = caps_of(&PROFILES[find("NextUI 64-bit")]), b;
	char text[1024];
	NS_engineCapsEncode(&a, text, sizeof(text));
	bool same = NS_engineCapsDecode(text, &b) && !memcmp(&a, &b, sizeof(a));
	printf("  %s %s\n", same ? "ok  " : "FAIL", text);
	if (!same) failures++;
	NS_engineCapsDecode("tier=2;arch=32;have=fceumm,some_future_core", &b);
	same = b.tier == 2 && b.is32 && b.have[NS_engineIndex("fceumm")];
	printf("  %s unknown engine names are ignored\n", same ? "ok  " : "FAIL");
	if (!same) failures++;

	printf("%s (%d failures)\n", failures ? "FAILED" : "ok", failures);
	return failures != 0;
}
